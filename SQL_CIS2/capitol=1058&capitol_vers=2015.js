// CAPITOL = 1058
// 17 coloane active
// ID_MD si RIND sunt preluate din CAPITOL_1058.xlsx

function sumCap1058Rows(rowIDs, targetId, targetRind) {
    var sums = [];
    var col;

    for (col = 1; col <= 17; col++) {
        sums[col] = 0;
    }

    rowIDs.forEach(function (row) {
        var escapedRind = row.rind.replace(/\./g, "\\.");

        for (col = 1; col <= 17; col++) {
            sums[col] += parseInt(
                $("#50_1058_" + row.id + "_" + escapedRind + "_" + col).val(),
                10
            ) || 0;
        }
    });

    for (col = 1; col <= 17; col++) {
        $("#50_1058_" + targetId + "_" + targetRind + "_" + col)
            .val(sums[col] !== 0 ? sums[col] : "")
            .prop("readonly", true);
    }
}


