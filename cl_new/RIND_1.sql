SELECT
    ID_MD,
    FORM,
    FORM_VERS,
    CAPITOL,
    CAPITOL_VERS,
    RIND,
    RIND_VERS,
    DENUMIRE,
    DECIMAL_POS,
    COL_ACTIV,
    ORDINE,
    DATA_REG,
    STATUT,
    DINAMIC
FROM CIS2.MD_RIND
WHERE 

  FORM = 49
  AND CAPITOL = 1049
  AND CAPITOL_VERS = 2015
  AND STATUT = '1'
  AND RIND  LIKE '1%'
  AND LENGTH(RIND) > 3
 -- AND ORDINE BETWEEN 1 AND 209
  
  
  
  ORDER BY 
  ORDINE